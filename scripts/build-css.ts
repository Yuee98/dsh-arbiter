import assert from 'node:assert/strict';
import { execFile } from 'node:child_process';
import { writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { promisify } from 'node:util';
import prettier from 'prettier';

const execFileAsync = promisify(execFile);

function getRoot(): string {
  try {
    const url = new URL('../', import.meta.url);
    if (url.protocol === 'file:') {
      return fileURLToPath(url);
    }
  } catch {
    // fallback
  }
  return resolve(process.cwd()) + '/';
}

const root = getRoot();
const inputCssPath = `${root}src/client/styles/tailwind.css`;
const outputTsPath = `${root}src/client/styles/compiled-css.ts`;

export function verifyCssInvariants(css: string): void {
  // Positive assertions
  assert.ok(
    css.includes('--dsw-alias-'),
    'CSS must include --dsw-alias- mappings',
  );
  assert.ok(
    css.includes(':where([data-arbiter-root], [data-arbiter-surface])'),
    'CSS must scope custom variables to [data-arbiter-root] and [data-arbiter-surface]',
  );

  // Negative isolation checks (A03):
  // 1. Zero bare Preflight resets outside of :where([data-arbiter-root], [data-arbiter-surface])
  const bareResets = [
    /\n(?:html|body|button|input|select|textarea|h1|h2|h3|h4|h5|h6|p|ol|ul|table)\s*\{/i,
    /\n\*\s*,\s*::after\s*,\s*::before\s*\{/i,
  ];
  for (const pattern of bareResets) {
    assert.ok(
      !pattern.test(css),
      `CSS must not contain global Preflight element resets matching ${pattern.source}`,
    );
  }

  // 2. Zero unprefixed utility selectors (e.g. .flex, .grid, .hidden, .truncate, .relative)
  const unprefixedUtility =
    /\n\.(?:flex|grid|hidden|truncate|relative|absolute|fixed|sticky)\s*\{/i;
  assert.ok(
    !unprefixedUtility.test(css),
    'CSS must not contain unprefixed utility classes outside arb:*',
  );
}

export async function buildCss(
  options: { write?: boolean } = {},
): Promise<string> {
  const shouldWrite = options.write ?? true;
  const tailwindBin = `${root}node_modules/.bin/tailwindcss`;

  const { stdout } = await execFileAsync(
    tailwindBin,
    ['--input', inputCssPath],
    {
      cwd: root,
      maxBuffer: 10 * 1024 * 1024,
    },
  );

  verifyCssInvariants(stdout);

  if (shouldWrite) {
    const rawContent = [
      '// This file is auto-generated by scripts/build-css.ts. Do not edit directly.',
      `export const ARBITER_COMPILED_CSS = ${JSON.stringify(stdout)};\n`,
    ].join('\n');
    const formattedContent = await prettier.format(rawContent, {
      filepath: outputTsPath,
    });
    await writeFile(outputTsPath, formattedContent, 'utf8');
  }

  return stdout;
}

if (
  typeof import.meta.url === 'string' &&
  import.meta.url.startsWith('file:') &&
  process.argv[1] === fileURLToPath(import.meta.url)
) {
  const css = await buildCss({ write: true });
  console.log(
    `Compiled and verified client CSS (${String(css.length)} bytes).`,
  );
}
